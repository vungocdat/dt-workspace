/**
 * One-off copy of a dt-workspace SQLite database (the pre-Postgres server/data/kb.db)
 * into the Postgres database named by DATABASE_URL.
 *
 *   npm -w server run db:import-sqlite -- /path/to/kb.db
 *
 * - Applies the app's migrations first, so the target can be a fresh, empty
 *   database (the same migrations the server runs on startup).
 * - Refuses to run if any app table already has rows — it never merges.
 * - Copies spaces → pages → calendar_notes → todos in ONE transaction, then
 *   reads every table back and compares row counts and a content checksum
 *   with the source; any mismatch rolls the whole copy back.
 * - The SQLite file is opened read-only. Only the four app tables are read:
 *   __drizzle_migrations and the FTS5 pages_fts* tables are SQLite-only
 *   (search_vector is generated by Postgres itself).
 * - Tolerates older databases: no calendar_notes / todos table, or a todos
 *   table from before the pinned column existed.
 *
 * Reads SQLite with Node's built-in node:sqlite (no native module to build).
 */
import { createHash } from 'node:crypto';
import { existsSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { config as loadEnv } from 'dotenv';

const USAGE = 'Usage: npm -w server run db:import-sqlite -- /path/to/kb.db';

type Kind = 'text' | 'textNull' | 'int' | 'intNull' | 'bool';
type Value = string | number | boolean | null;

interface ColumnSpec {
  name: string;
  kind: Kind;
  /** Used when the source table predates this column. */
  fallback?: Value;
}

interface TableSpec {
  name: string;
  pk: string;
  /** spaces and pages must exist in any dt-workspace database; the others came later. */
  required: boolean;
  columns: ColumnSpec[];
}

// Insert order matters: pages.space_id references spaces.
const TABLES: TableSpec[] = [
  {
    name: 'spaces',
    pk: 'id',
    required: true,
    columns: [
      { name: 'id', kind: 'text' },
      { name: 'name', kind: 'text' },
      { name: 'description', kind: 'text' },
      { name: 'icon', kind: 'text' },
      { name: 'sort_order', kind: 'int' },
      { name: 'created_at', kind: 'int' },
      { name: 'updated_at', kind: 'int' },
    ],
  },
  {
    name: 'pages',
    pk: 'id',
    required: true,
    columns: [
      { name: 'id', kind: 'text' },
      { name: 'space_id', kind: 'text' },
      { name: 'parent_id', kind: 'textNull' },
      { name: 'title', kind: 'text' },
      { name: 'content', kind: 'text' },
      { name: 'content_html', kind: 'text' },
      { name: 'sort_order', kind: 'int' },
      { name: 'created_at', kind: 'int' },
      { name: 'updated_at', kind: 'int' },
    ],
  },
  {
    name: 'calendar_notes',
    pk: 'date',
    required: false,
    columns: [
      { name: 'date', kind: 'text' },
      { name: 'content', kind: 'text' },
      { name: 'content_html', kind: 'text' },
      { name: 'created_at', kind: 'int' },
      { name: 'updated_at', kind: 'int' },
    ],
  },
  {
    name: 'todos',
    pk: 'id',
    required: false,
    columns: [
      { name: 'id', kind: 'text' },
      { name: 'title', kind: 'text' },
      { name: 'done', kind: 'bool' },
      { name: 'sort_order', kind: 'int' },
      { name: 'pinned', kind: 'bool', fallback: false },
      { name: 'created_at', kind: 'int' },
      { name: 'updated_at', kind: 'int' },
      { name: 'completed_at', kind: 'intNull' },
    ],
  },
];

const SQLITE_ONLY_TABLES = /^(__drizzle_migrations|pages_fts.*|sqlite_.*)$/;

class ImportError extends Error {}

/**
 * Convert one SQLite value to what Postgres should store. SQLite's loose
 * typing means a column can hold anything; fail loudly on what the app would
 * never have written instead of guessing.
 */
function convert(value: unknown, col: ColumnSpec, where: string): Value {
  const fail = (expected: string): never => {
    throw new ImportError(`${where}.${col.name}: expected ${expected}, got ${JSON.stringify(value)}`);
  };
  if (value === null || value === undefined) {
    if (col.kind === 'textNull' || col.kind === 'intNull') return null;
    return fail(`a non-null ${col.kind}`);
  }
  switch (col.kind) {
    case 'text':
    case 'textNull':
      return typeof value === 'string' ? value : fail('text');
    case 'int':
    case 'intNull': {
      const n = typeof value === 'bigint' ? Number(value) : value;
      return typeof n === 'number' && Number.isSafeInteger(n) ? n : fail('an integer');
    }
    case 'bool':
      return value === 0 || value === 1 ? value === 1 : fail('0 or 1');
  }
}

const byPk = (a: Value[], b: Value[]) => {
  const x = a[0] as string;
  const y = b[0] as string;
  return x < y ? -1 : x > y ? 1 : 0;
};

/** Order-independent checksum of a table's rows (pk is always column 0). */
function checksum(rows: Value[][]): string {
  const sorted = [...rows].sort(byPk);
  return createHash('sha256').update(JSON.stringify(sorted)).digest('hex');
}

/** Put the pk first so sorting and checksums line up on both sides. */
function orderedColumns(spec: TableSpec): ColumnSpec[] {
  return [
    spec.columns.find((c) => c.name === spec.pk)!,
    ...spec.columns.filter((c) => c.name !== spec.pk),
  ];
}

async function main(): Promise<void> {
  const arg = process.argv[2];
  if (!arg || arg === '-h' || arg === '--help') {
    console.error(USAGE);
    process.exit(arg ? 0 : 2);
  }

  // npm -w runs scripts with cwd = server/, so a relative path means relative
  // to where the user typed the command (INIT_CWD), not to server/.
  const sqlitePath = resolve(process.env.INIT_CWD ?? process.cwd(), arg);
  if (!existsSync(sqlitePath)) {
    console.error(`No such file: ${sqlitePath}`);
    process.exit(2);
  }

  // Same environment as the server: find server/ (works from scripts/ under
  // tsx and from dist/scripts/ when built), make it the working directory so
  // ./db/migrations resolves, and load the repo-root .env. Variables already
  // set in the environment win (dotenv doesn't override them).
  let serverDir = dirname(fileURLToPath(import.meta.url));
  while (!existsSync(join(serverDir, 'package.json'))) serverDir = dirname(serverDir);
  process.chdir(serverDir);
  loadEnv({ path: resolve(serverDir, '../.env') });

  // node:sqlite is stable enough on Node 22 but still prints an
  // ExperimentalWarning when loaded; silence just that one.
  const emitWarning = process.emitWarning.bind(process);
  process.emitWarning = ((warning: string | Error, ...rest: unknown[]) => {
    const message = typeof warning === 'string' ? warning : warning.message;
    if (/SQLite/i.test(message)) return;
    (emitWarning as (...args: unknown[]) => void)(warning, ...rest);
  }) as typeof process.emitWarning;
  const { DatabaseSync } = await import('node:sqlite');

  // Imported after .env is loaded: client.ts reads DATABASE_URL at load.
  const { pool, runMigrations, withTransaction, many, one } = await import('../db/client.js');

  const source = new DatabaseSync(sqlitePath, { readOnly: true });
  try {
    const sourceTables = new Set(
      (source.prepare(`SELECT name FROM sqlite_master WHERE type = 'table'`).all() as { name: string }[]).map(
        (r) => r.name,
      ),
    );

    // ── Read and convert everything before touching Postgres ──
    const data = new Map<string, Value[][]>();
    for (const spec of TABLES) {
      if (!sourceTables.has(spec.name)) {
        if (spec.required) {
          throw new ImportError(`${sqlitePath} has no ${spec.name} table — is it a dt-workspace database?`);
        }
        data.set(spec.name, []);
        continue;
      }
      const present = new Set(
        (source.prepare(`PRAGMA table_info(${spec.name})`).all() as { name: string }[]).map((r) => r.name),
      );
      const cols = orderedColumns(spec);
      for (const col of cols) {
        if (!present.has(col.name) && col.fallback === undefined) {
          throw new ImportError(`${spec.name} is missing column ${col.name}`);
        }
      }
      // Positional aliases: rows come back as objects keyed by column name.
      const select = cols
        .map((c, j) => `${present.has(c.name) ? `"${c.name}"` : 'NULL'} AS c${j}`)
        .join(', ');
      const rows = source.prepare(`SELECT ${select} FROM ${spec.name}`).all() as Record<string, unknown>[];
      data.set(
        spec.name,
        rows.map((row, i) =>
          cols.map((col, j) =>
            present.has(col.name) ? convert(row[`c${j}`], col, `${spec.name}[${i}]`) : col.fallback!,
          ),
        ),
      );
    }

    const skipped = [...sourceTables].filter(
      (t) => !TABLES.some((s) => s.name === t) && !SQLITE_ONLY_TABLES.test(t),
    );

    // ── Postgres ──
    await runMigrations();
    const target = await one<{ db: string }>('SELECT current_database() AS db');

    const results = await withTransaction(async (tx) => {
      // Block concurrent writes (e.g. a running server) for the duration of
      // the copy; reads still work. Then make sure we start from nothing.
      await tx.query(`LOCK TABLE ${TABLES.map((t) => t.name).join(', ')} IN EXCLUSIVE MODE`);
      const counts = await many<Record<string, number>>(
        `SELECT ${TABLES.map((t) => `(SELECT count(*) FROM ${t.name}) AS ${t.name}`).join(', ')}`,
        [],
        tx,
      );
      const nonEmpty = TABLES.filter((t) => counts[0]![t.name]! > 0).map(
        (t) => `${t.name} (${counts[0]![t.name]} rows)`,
      );
      if (nonEmpty.length > 0) {
        throw new ImportError(
          `Refusing to import: database "${target?.db}" already has data in ${nonEmpty.join(', ')}. ` +
            'This script only fills an empty database.',
        );
      }

      const summary: { table: string; rows: number; checksum: string }[] = [];
      for (const spec of TABLES) {
        const cols = orderedColumns(spec);
        const rows = data.get(spec.name)!;
        const colList = cols.map((c) => c.name).join(', ');

        // Multi-row INSERTs in chunks, well under Postgres' 65535-parameter cap.
        const CHUNK = 200;
        for (let i = 0; i < rows.length; i += CHUNK) {
          const chunk = rows.slice(i, i + CHUNK);
          const params: Value[] = [];
          const tuples = chunk.map((row) => {
            const placeholders = row.map((v) => {
              params.push(v);
              return `$${params.length}`;
            });
            return `(${placeholders.join(', ')})`;
          });
          await tx.query(`INSERT INTO ${spec.name} (${colList}) VALUES ${tuples.join(', ')}`, params);
        }

        // Read back what Postgres stored and compare with what we read.
        const stored = (await many<Record<string, Value>>(`SELECT ${colList} FROM ${spec.name}`, [], tx)).map(
          (r) => cols.map((c) => r[c.name] ?? null),
        );
        const expected = checksum(rows);
        const actual = checksum(stored);
        if (stored.length !== rows.length || actual !== expected) {
          throw new ImportError(
            `Verification failed for ${spec.name}: source ${rows.length} rows (${expected.slice(0, 12)}), ` +
              `Postgres ${stored.length} rows (${actual.slice(0, 12)}). Rolled back.`,
          );
        }
        summary.push({ table: spec.name, rows: rows.length, checksum: actual });
      }
      return summary;
    });

    console.log(`Imported ${sqlitePath}`);
    console.log(`into Postgres database "${target?.db}":`);
    for (const r of results) {
      console.log(`  ${r.table.padEnd(15)} ${String(r.rows).padStart(5)} rows   sha256 ${r.checksum.slice(0, 12)}`);
    }
    console.log('Row counts and content checksums match the source.');
    if (skipped.length > 0) {
      console.log(`Not copied (unknown to this app): ${skipped.join(', ')}`);
    }
  } finally {
    source.close();
    await pool.end();
  }
}

main().catch((err: unknown) => {
  if (err instanceof ImportError) {
    console.error(err.message);
  } else {
    console.error('Import failed; no rows were copied:', err);
  }
  process.exit(1);
});
